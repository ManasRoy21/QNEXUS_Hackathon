"""Canonical Simulation State Store — in-process session registry.

A lightweight in-memory dictionary keyed by simulation_id that holds
CanonicalSimulationState objects.  This allows POST /api/v1/simulation/attack
to retrieve state generated by POST /api/v1/simulation/generate-material without
requiring a database.

Thread-safety: dict operations in CPython are GIL-protected.
For production use, replace with a Redis-backed store.
"""

from __future__ import annotations

from typing import Dict, Optional

from app.schemas.canonical_models import CanonicalSimulationState

_store: Dict[str, CanonicalSimulationState] = {}


def save(state: CanonicalSimulationState) -> None:
    """Persist a canonical simulation state by its simulation_id."""
    _store[state.simulation_id] = state


def get(simulation_id: str) -> Optional[CanonicalSimulationState]:
    """Retrieve a simulation state by ID, or None if not found."""
    return _store.get(simulation_id)


def require(simulation_id: str) -> CanonicalSimulationState:
    """Retrieve a simulation state by ID.

    Raises LookupError if the simulation_id is not found.
    """
    state = _store.get(simulation_id)
    if state is None:
        raise LookupError(
            f"No simulation state found for simulation_id='{simulation_id}'. "
            "Run POST /api/v1/simulation/generate-material first."
        )
    return state


def delete(simulation_id: str) -> bool:
    """Remove a simulation state. Returns True if it existed."""
    return _store.pop(simulation_id, None) is not None


def list_ids() -> list[str]:
    """Return all stored simulation IDs."""
    return list(_store.keys())


def clear() -> None:
    """Clear all stored states (used in tests)."""
    _store.clear()
