"""Module D: Pluggable Attack Injection Engine.

Provides a unified, object-oriented attack injection interface supporting
the 5 QDS threat classes:
- INTERCEPT_RESEND_EAVESDROPPING (Physical quantum channel eavesdropping)
- FORGERY (Classical/quantum payload bit & basis tampering)
- IMPERSONATION (Signer public key identity spoofing)
- REPLAY (Stale timestamp & duplicate transaction nonce)
- REPUDIATION (Dishonest Alice distributing inconsistent states to Bob vs. Charlie)
"""

import random
from copy import deepcopy
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Tuple

from app.engine.protocol.qds_protocol import QDSSignatureBlock
from app.engine.threats.channel_noise import AdversaryChannel


class AttackType(str, Enum):
    """Supported QDS attack type categories."""

    CLEAN = "CLEAN"
    INTERCEPT_RESEND = "INTERCEPT_RESEND"
    FORGERY = "FORGERY"
    IMPERSONATION = "IMPERSONATION"
    REPLAY = "REPLAY"
    REPUDIATION = "REPUDIATION"
    DETECTOR_SIDE_CHANNEL = "DETECTOR_SIDE_CHANNEL"


@dataclass
class AttackConfig:
    """Parameterised configuration controlling attack injection behaviour.

    Attributes:
        attack_type: Which cryptanalytic attack vector to activate.
        intensity: Generic scalar controlling tamper_rate / eavesdrop_probability (0.0–1.0).
        spoofed_public_key: Forged signer identity credential for impersonation attacks.
        replay_age_seconds: Seconds elapsed since original packet transmission (replay attacks).
        asymmetry_rate: Fraction of signature bits Alice corrupts for Charlie in repudiation attacks (0.0–1.0).
        path_bias_intensity: Bias intensity for detector side-channel tampering (0.0-1.0, default 0.45).
    """

    attack_type: AttackType
    intensity: float = 0.3
    spoofed_public_key: str = "mallory-unauthorized-key-0xDEADBEEF"
    replay_age_seconds: float = 300.0
    asymmetry_rate: float = 0.4
    path_bias_intensity: float = 0.45


class AttackSimulator:
    """Applies pluggable attack transformations to QDSSignatureBlock payloads.

    Architecture:
        - CLEAN: No modification; packet passes through unchanged.
        - INTERCEPT_RESEND: Marks packet for physical channel eavesdropping simulation.
          The caller must also supply adversary-corrupted measurement counts to the detector.
        - FORGERY: Flips digest bits, inverts bases, and tags the tampered flag.
        - IMPERSONATION: Overwrites signer_public_key with spoofed credentials.
        - REPLAY: Rewinds packet timestamp and preserves original nonce.
        - REPUDIATION: Dishonest-Alice distributes a clean block to Bob but a
          state-inconsistent block to Charlie, attempting verifier disagreement.
    """

    _adversary: AdversaryChannel = AdversaryChannel()

    @staticmethod
    def inject_attack(
        packet: QDSSignatureBlock,
        config: AttackConfig,
    ) -> Tuple[QDSSignatureBlock, Dict[str, Any]]:
        """Applies the configured attack transformation to a QDSSignatureBlock.

        Args:
            packet: A valid QDSSignatureBlock generated by QDSProtocolEngine.
            config: AttackConfig specifying the attack vector and parameters.

        Returns:
            Tuple of:
              - Modified QDSSignatureBlock (altered in-place copy).
              - injection_metadata dict detailing what was altered.

        Note:
            For REPUDIATION attacks use `simulate_repudiation_attack` directly,
            as it returns two independent blocks (one for Bob, one for Charlie).
            `inject_attack` for REPUDIATION returns the *Charlie* (corrupted) block.
        """
        adversary = AttackSimulator._adversary
        attack_type = config.attack_type
        metadata: Dict[str, Any] = {
            "attack_type": attack_type.value,
            "intensity": config.intensity,
        }

        if attack_type == AttackType.CLEAN:
            metadata["description"] = "No modification applied. Packet is legitimate."
            return packet, metadata

        if attack_type == AttackType.INTERCEPT_RESEND:
            # Metadata-level mark: the caller must wire up eavesdropped counts to the detector.
            # The packet itself remains authentic; the quantum channel is corrupted externally.
            metadata["description"] = (
                "Intercept-Resend eavesdropping flagged on transit channel. "
                "Corrupted quantum measurement counts must be supplied to detector."
            )
            metadata["eavesdrop_probability"] = config.intensity
            packet.public_key_registers["intercept_resend_active"] = True
            packet.public_key_registers["eavesdrop_probability"] = config.intensity
            return packet, metadata

        if attack_type == AttackType.FORGERY:
            original_digest = packet.digest
            tampered = adversary.simulate_forgery_attack(packet, tamper_rate=config.intensity)
            metadata["description"] = (
                f"Payload forgery injected at tamper_rate={config.intensity:.0%}: "
                f"digest {original_digest} -> {tampered.digest}"
            )
            metadata["original_digest"] = original_digest
            metadata["tampered_digest"] = tampered.digest
            metadata["tampered_indices"] = tampered.public_key_registers.get("tampered_indices", [])
            return tampered, metadata

        if attack_type == AttackType.IMPERSONATION:
            original_key = packet.signer_public_key
            spoofed = adversary.simulate_impersonation_attack(
                packet,
                forged_public_key=config.spoofed_public_key,
            )
            metadata["description"] = (
                f"Signer identity spoofed: '{original_key}' -> '{config.spoofed_public_key}'"
            )
            metadata["original_public_key"] = original_key
            metadata["spoofed_public_key"] = config.spoofed_public_key
            return spoofed, metadata

        if attack_type == AttackType.REPLAY:
            replayed = adversary.simulate_replay_attack(
                packet,
                age_seconds=config.replay_age_seconds,
            )
            metadata["description"] = (
                f"Replay attack: packet timestamp rewound by {config.replay_age_seconds:.0f}s."
            )
            metadata["replay_age_seconds"] = config.replay_age_seconds
            metadata["original_nonce"] = packet.nonce
            return replayed, metadata

        if attack_type == AttackType.REPUDIATION:
            bob_block, charlie_block = AttackSimulator.simulate_repudiation_attack(
                packet,
                asymmetry_rate=config.asymmetry_rate,
            )
            metadata["description"] = (
                f"Repudiation attack: dishonest Alice distributed inconsistent states "
                f"to Bob (clean) vs. Charlie (corrupted at asymmetry_rate={config.asymmetry_rate:.0%})."
            )
            metadata["asymmetry_rate"] = config.asymmetry_rate
            metadata["bob_block"] = bob_block
            metadata["charlie_block"] = charlie_block
            # Return the Charlie (corrupted) block as the primary output for compatibility
            return charlie_block, metadata

        if attack_type == AttackType.DETECTOR_SIDE_CHANNEL:
            bias_val = (
                config.path_bias_intensity
                if config.path_bias_intensity != 0.45 or config.intensity == 0.3
                else config.intensity
            )
            biased_packet, meta = AttackSimulator.simulate_detector_side_channel_attack(
                packet,
                path_bias_intensity=bias_val,
            )
            return biased_packet, meta

        raise ValueError(f"Unsupported AttackType: {attack_type!r}")

    @staticmethod
    def simulate_repudiation_attack(
        signature_packet: QDSSignatureBlock,
        asymmetry_rate: float = 0.4,
        seed: int = None,
    ) -> Tuple[QDSSignatureBlock, QDSSignatureBlock]:
        """Models a dishonest-Alice repudiation attack by distributing inconsistent states.

        Alice prepares a legitimate state preparation block for Bob, then independently
        prepares a corrupted variant for Charlie by flipping target_bases and pauli_states
        at a fraction `asymmetry_rate` of the signature positions. Without symmetrization,
        Bob verifies CLEAN while Charlie detects high QBER, creating verifier disagreement.

        Args:
            signature_packet: A valid QDSSignatureBlock (treated as Alice's template).
            asymmetry_rate: Fraction of bits Alice corrupts for Charlie (0.0–1.0, default 0.4).
            seed: Optional RNG seed for reproducible experiments.

        Returns:
            Tuple of:
              - bob_block: Clean (unmodified) QDSSignatureBlock given to Bob.
              - charlie_block: Corrupted QDSSignatureBlock given to Charlie, with
                  asymmetric bases, flipped Pauli states, and repudiation flag set.
        """
        if not 0.0 <= asymmetry_rate <= 1.0:
            raise ValueError(f"asymmetry_rate must be in [0.0, 1.0], got {asymmetry_rate}")

        # Bob receives the legitimate, unaltered block
        bob_block = deepcopy(signature_packet)
        bob_block.public_key_registers["recipient"] = "bob"

        # Charlie receives a deliberately corrupted block
        charlie_block = deepcopy(signature_packet)
        charlie_block.public_key_registers["recipient"] = "charlie"
        charlie_block.public_key_registers["repudiation_attempt"] = True

        n_bits = len(signature_packet.target_bases)
        n_corrupt = max(1, round(asymmetry_rate * n_bits))

        rng = random.Random(seed)
        corrupt_indices: List[int] = sorted(rng.sample(range(n_bits), min(n_corrupt, n_bits)))

        # Basis flip mapping (Z <-> X)
        basis_flip: Dict[str, str] = {"Z": "X", "X": "Z"}

        # Pauli state flip mapping (within-basis inversion)
        state_flip: Dict[str, str] = {"0": "1", "1": "0", "+": "-", "-": "+"}

        for idx in corrupt_indices:
            original_basis = charlie_block.target_bases[idx]
            original_state = charlie_block.pauli_states[idx]
            charlie_block.target_bases[idx] = basis_flip.get(original_basis, original_basis)
            charlie_block.pauli_states[idx] = state_flip.get(original_state, original_state)

        charlie_block.public_key_registers["corrupted_indices"] = corrupt_indices
        charlie_block.public_key_registers["asymmetry_rate"] = asymmetry_rate

        return bob_block, charlie_block

    @staticmethod
    def simulate_detector_side_channel_attack(
        signature_packet: QDSSignatureBlock,
        path_bias_intensity: float = 0.45,
        shots: int = 4096,
    ) -> Tuple[QDSSignatureBlock, Dict[str, Any]]:
        """Simulates detector side-channel tampering / blinding on measurement Path B.

        Modifies the signature block to include dual-path measurement telemetry
        ('measurement_path_a' and 'measurement_path_b'). Path A contains valid simulated
        measurement results, while Path B is silently biased (e.g. forcing outcomes toward
        a saturation state) to simulate detector tampering or blinding.

        Args:
            signature_packet: Original valid QDSSignatureBlock.
            path_bias_intensity: Fraction of measurement outcomes biased/blinded (0.0-1.0, default 0.45).
            shots: Measurement shot sample size (default 4096).

        Returns:
            Tuple of:
              - Updated QDSSignatureBlock with dual-path telemetry embedded.
              - injection_metadata dictionary detailing detector path B compromise.
        """
        packet = deepcopy(signature_packet)
        digest = packet.digest
        n_bits = len(digest)

        # Path A: Valid simulated measurement outcomes matching authentic digest
        path_a_counts: Dict[str, int] = {digest: shots}

        # Path B: Silently biased distribution (detector tampering/blinding)
        blinded_count = max(1, round(path_bias_intensity * shots))
        legit_count = shots - blinded_count

        # Saturated blinding pattern (e.g. all-zeros |00...0> detector saturation)
        blinded_pattern = "0" * n_bits
        if blinded_pattern == digest:
            blinded_pattern = "1" * n_bits

        path_b_counts: Dict[str, int] = {
            digest: legit_count,
            blinded_pattern: blinded_count,
        }

        packet.public_key_registers["measurement_path_a"] = path_a_counts
        packet.public_key_registers["measurement_path_b"] = path_b_counts
        packet.public_key_registers["detector_side_channel_compromise"] = True
        packet.public_key_registers["path_bias_intensity"] = path_bias_intensity

        metadata: Dict[str, Any] = {
            "attack_type": AttackType.DETECTOR_SIDE_CHANNEL.value,
            "path_bias_intensity": path_bias_intensity,
            "path_a_counts": path_a_counts,
            "path_b_counts": path_b_counts,
            "description": (
                f"Detector side-channel blinding attack injected: Path A clean ({shots} shots), "
                f"Path B biased at {path_bias_intensity:.0%} ({blinded_count}/{shots} blinded to '{blinded_pattern}')."
            ),
        }
        return packet, metadata

    @staticmethod
    def generate_clean_dual_path(
        signature_packet: QDSSignatureBlock,
        shots: int = 4096,
    ) -> Tuple[QDSSignatureBlock, Dict[str, Any]]:
        """Generates legitimate dual-path measurement telemetry (Path A == Path B).

        Args:
            signature_packet: Original valid QDSSignatureBlock.
            shots: Measurement shot sample size (default 4096).

        Returns:
            Tuple of:
              - Updated QDSSignatureBlock with aligned dual-path telemetry.
              - metadata dictionary confirming clean baseline.
        """
        packet = deepcopy(signature_packet)
        digest = packet.digest
        counts = {digest: shots}
        packet.public_key_registers["measurement_path_a"] = deepcopy(counts)
        packet.public_key_registers["measurement_path_b"] = deepcopy(counts)
        packet.public_key_registers["detector_side_channel_compromise"] = False

        metadata: Dict[str, Any] = {
            "attack_type": AttackType.CLEAN.value,
            "path_a_counts": counts,
            "path_b_counts": counts,
            "description": "Clean dual-path telemetry generated: Path A and Path B aligned (zero divergence).",
        }
        return packet, metadata

    @staticmethod
    def attach_boundary_noise(
        counts: Dict[str, int],
        noise_fraction: float = 0.03,
        boundary_tag: str = "ambiguous",
    ) -> Dict[str, int]:
        """Injects realistic ambiguous boundary zone shots into a measurement distribution.

        Used to demonstrate postselection filtering: a small fraction (default 3%)
        of shots are distributed into marginal/boundary noise tokens that postselection
        subsequently identifies and discards.

        Args:
            counts: Input count dictionary {bitstring: shots}.
            noise_fraction: Proportion of shots placed in the ambiguous zone (default 0.03).
            boundary_tag: Label tag appended to ambiguous bitstring keys.

        Returns:
            Count dictionary containing both core distribution and boundary noise states.
        """
        if not counts:
            return {}
        total = sum(counts.values())
        n_noise = max(1, round(noise_fraction * total))

        # Find dominant state to bleed noise from
        dominant_key = max(counts, key=counts.get)
        dominant_count = counts[dominant_key]

        noisy_counts = dict(counts)
        noisy_counts[dominant_key] = max(1, dominant_count - n_noise)
        ambiguous_key = f"{dominant_key}_{boundary_tag}"
        noisy_counts[ambiguous_key] = n_noise

        return noisy_counts

    @staticmethod
    def generate_noisy_channel_counts(
        digest: str,
        total_shots: int = 4096,
        noise_fraction: float = 0.03,
    ) -> Dict[str, int]:
        """Generates an authentic signal stream with realistic marginal boundary noise."""
        clean = {digest: total_shots}
        return AttackSimulator.attach_boundary_noise(clean, noise_fraction=noise_fraction)
